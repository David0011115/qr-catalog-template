create or replace function public.kapli_mod_my_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare s record;
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;

  select id, kind, reason, created_at, ends_at
    into s
  from public.kapli_sanctions
  where user_id = auth.uid()
    and revoked_at is null
    and (kind = 'ban' or ends_at > now())
  order by case when kind = 'ban' then 0 else 1 end, ends_at desc nulls first
  limit 1;

  if not found then
    return jsonb_build_object('active', false);
  end if;

  return jsonb_build_object(
    'active', true,
    'id', s.id,
    'kind', s.kind,
    'reason', s.reason,
    'created_at', s.created_at,
    'ends_at', s.ends_at
  );
end;
$$;

-- Internal function: call only from trusted server-side moderation logic.
-- Daily counters use UTC dates; historical violation rows are never deleted at midnight.
create or replace function public.kapli_mod_record_violation(
  p_user_id uuid,
  p_type text,
  p_source text,
  p_source_id bigint default null,
  p_body text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  d date := (now() at time zone 'UTC')::date;
  n integer;
  mins integer;
  expiry timestamptz;
  active_id bigint;
begin
  if p_user_id is null or p_type is null or p_type not in ('insult','spam') then
    raise exception 'invalid_violation' using errcode = 'P0001';
  end if;
  if p_source is null or p_source not in ('chat','dm','manual','system') then
    raise exception 'invalid_source' using errcode = 'P0001';
  end if;

  insert into public.kapli_moderation_counters(user_id, violation_type, day_utc, violation_count, updated_at)
  values (p_user_id, p_type, d, 1, now())
  on conflict (user_id, violation_type, day_utc)
  do update set violation_count = public.kapli_moderation_counters.violation_count + 1,
                updated_at = now()
  returning violation_count into n;

  mins := n * 5;
  insert into public.kapli_moderation_violations
    (user_id, violation_type, source, source_id, body_snapshot, day_utc, count_for_day, mute_minutes)
  values
    (p_user_id, p_type, p_source, p_source_id, left(coalesce(p_body,''), 1000), d, n, mins);

  expiry := now() + make_interval(mins => mins);
  select id into active_id
  from public.kapli_sanctions
  where user_id = p_user_id and kind = 'mute' and source = 'automatic'
    and revoked_at is null and ends_at > now()
  order by ends_at desc
  limit 1;

  if active_id is null then
    insert into public.kapli_sanctions(user_id, kind, reason, source, ends_at)
    values (p_user_id, 'mute', case p_type when 'insult' then 'Оскорбления' else 'Спам или флуд' end, 'automatic', expiry);
  else
    update public.kapli_sanctions
       set ends_at = greatest(ends_at, expiry),
           reason = case p_type when 'insult' then 'Оскорбления' else 'Спам или флуд' end
     where id = active_id;
  end if;

  return jsonb_build_object('count', n, 'mute_minutes', mins, 'day_utc', d);
end;
$$;

create or replace function public.kapli_mod_submit_appeal(p_sanction_id bigint, p_body text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare new_id bigint;
begin
  if auth.uid() is null then raise exception 'not_authenticated' using errcode = 'P0001'; end if;
  if char_length(trim(coalesce(p_body,''))) < 10 or char_length(p_body) > 2000 then
    raise exception 'appeal_length' using errcode = 'P0001';
  end if;
  if not exists (
    select 1 from public.kapli_sanctions s
    where s.id = p_sanction_id and s.user_id = auth.uid()
  ) then raise exception 'sanction_not_found' using errcode = 'P0001'; end if;

  insert into public.kapli_moderation_appeals(sanction_id, user_id, body)
  values (p_sanction_id, auth.uid(), trim(p_body))
  returning id into new_id;
  return new_id;
exception when unique_violation then
  raise exception 'appeal_already_sent' using errcode = 'P0001';
end;
$$;

create or replace function public.kapli_mod_submit_suspicious_event(
  p_event_type text,
  p_evidence jsonb,
  p_match_id uuid default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare new_id bigint;
begin
  if auth.uid() is null then raise exception 'not_authenticated' using errcode = 'P0001'; end if;
  if p_event_type not in ('impossible_move','cooldown_abuse','resource_anomaly','result_anomaly','request_tampering','repeated_anomaly','other') then
    raise exception 'invalid_event_type' using errcode = 'P0001';
  end if;
  if octet_length(coalesce(p_evidence, '{}'::jsonb)::text) > 12000 then
    raise exception 'evidence_too_large' using errcode = 'P0001';
  end if;
  if (select count(*) from public.kapli_suspicious_events e
      where e.user_id = auth.uid() and e.created_at > now() - interval '1 minute') >= 30 then
    raise exception 'event_rate_limited' using errcode = 'P0001';
  end if;
  insert into public.kapli_suspicious_events(user_id, match_id, event_type, evidence)
  values (auth.uid(), p_match_id, p_event_type, coalesce(p_evidence, '{}'::jsonb))
  returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.kapli_mod_admin_dashboard()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.kapli_mod_is_admin() then raise exception 'admin_only' using errcode = 'P0001'; end if;
  return jsonb_build_object(
    'queue_pending', (select count(*) from public.kapli_moderation_queue where status in ('pending','in_review')),
    'appeals_pending', (select count(*) from public.kapli_moderation_appeals where status = 'pending'),
    'events_new', (select count(*) from public.kapli_suspicious_events where review_status in ('new','reviewing')),
    'active_mutes', (select count(*) from public.kapli_sanctions where kind = 'mute' and revoked_at is null and ends_at > now()),
    'active_bans', (select count(*) from public.kapli_sanctions where kind = 'ban' and revoked_at is null)
  );
end;
$$;

create or replace function public.kapli_mod_admin_queue(p_status text default 'pending')
returns table (
  id bigint, category text, priority text, status text,
  reported_user_id uuid, reported_nickname text, reporter_user_id uuid,
  source text, source_id bigint, evidence jsonb, created_at timestamptz,
  resolution text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.kapli_mod_is_admin() then raise exception 'admin_only' using errcode = 'P0001'; end if;
  return query
  select q.id, q.category, q.priority, q.status, q.reported_user_id,
         p.nickname, q.reporter_user_id, q.source, q.source_id, q.evidence, q.created_at, q.resolution
  from public.kapli_moderation_queue q
  left join public.player_profiles p on p.user_id = q.reported_user_id
  where p_status = 'all' or q.status = p_status
  order by case q.priority when 'urgent' then 0 when 'high' then 1 when 'normal' then 2 else 3 end,
           q.created_at desc
  limit 200;
end;
$$;

