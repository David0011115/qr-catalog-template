-- KAPLI-3D TEST ONLY · public chat table + server-side moderation
-- Target: test project kccwtpveezsrgwfnflhf
-- Requires 001-moderation-core.sql and player_profiles / kapli_banned_words.
-- Client contract: insert {body}; select id,nickname,body,created_at; read last 3 days.
-- Moderated messages are rejected by returning NULL from the BEFORE INSERT trigger.
-- This migration does not seed the banned-word dictionary or invent flood thresholds.

begin;

create table if not exists public.kapli_chat (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nickname text not null,
  body text not null,
  created_at timestamptz not null default now(),
  constraint kapli_chat_body_length check (char_length(btrim(body)) between 1 and 500)
);

create index if not exists kapli_chat_created_id_idx
  on public.kapli_chat (created_at desc, id desc);

alter table public.kapli_chat enable row level security;

drop policy if exists kapli_chat_read on public.kapli_chat;
create policy kapli_chat_read
  on public.kapli_chat for select
  to anon, authenticated
  using (created_at > now() - interval '3 days');

drop policy if exists kapli_chat_write on public.kapli_chat;
create policy kapli_chat_write
  on public.kapli_chat for insert
  to authenticated
  with check (auth.uid() = user_id);

grant select on public.kapli_chat to anon, authenticated;
grant insert on public.kapli_chat to authenticated;
grant usage, select on sequence public.kapli_chat_id_seq to authenticated;

create or replace function public.kapli_chat_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  nick text;
  clean_body text := btrim(coalesce(new.body, ''));
  banned_kind text;
begin
  if me is null then
    raise exception 'not_signed_in' using errcode = 'P0001';
  end if;

  if clean_body = '' or char_length(clean_body) > 500 then
    raise exception 'invalid_message' using errcode = 'P0001';
  end if;

  if exists (
    select 1 from public.kapli_sanctions s
    where s.user_id = me and s.revoked_at is null
      and s.kind = 'ban'
  ) then
    raise exception 'banned' using errcode = 'P0001';
  end if;

  if exists (
    select 1 from public.kapli_sanctions s
    where s.user_id = me and s.revoked_at is null
      and s.kind = 'mute' and s.ends_at > now()
  ) then
    raise exception 'muted' using errcode = 'P0001';
  end if;

  select p.nickname into nick
  from public.player_profiles p
  where p.user_id = me;

  if nick is null or btrim(nick) = '' then
    raise exception 'profile_missing' using errcode = 'P0001';
  end if;

  banned_kind := public.kapli_text_banned(clean_body);
  if banned_kind is not null then
    if banned_kind in ('insult', 'spam') then
      perform public.kapli_mod_record_violation(me, banned_kind, 'chat', null, clean_body);
    end if;
    return null;
  end if;

  new.user_id := me;
  new.nickname := nick;
  new.body := clean_body;
  new.created_at := now();
  return new;
end;
$$;

drop trigger if exists kapli_chat_before_insert on public.kapli_chat;
create trigger kapli_chat_before_insert
before insert on public.kapli_chat
for each row execute function public.kapli_chat_before_insert();

-- Enable realtime only if the publication exists and the table is not already included.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'kapli_chat'
     ) then
    execute 'alter publication supabase_realtime add table public.kapli_chat';
  end if;
end;
$$;

commit;

-- Notes:
-- * Dictionary rows with kind='insult' or kind='spam' are required for automatic sanctions.
-- * Unknown dictionary kinds block the message but do not cause an automatic sanction.
-- * Flood detection is intentionally not added: no threshold was approved.
-- * The BEFORE INSERT trigger enforces mutes/bans even if a client bypasses the UI.
