-- Add a distinct temporary account ban. Existing permanent bans remain kind='ban'.
alter table public.kapli_sanctions drop constraint if exists kapli_sanctions_kind_check;
alter table public.kapli_sanctions drop constraint if exists kapli_sanctions_check;
alter table public.kapli_sanctions
  add constraint kapli_sanctions_kind_check check (kind in ('mute','temp_ban','ban'));
alter table public.kapli_sanctions drop constraint if exists kapli_sanctions_duration_check;
alter table public.kapli_sanctions
  add constraint kapli_sanctions_duration_check
  check ((kind = 'ban' and ends_at is null) or kind = 'mute' or (kind = 'temp_ban' and ends_at is not null));

create index if not exists kapli_sanctions_active_kind_idx
  on public.kapli_sanctions(kind, ends_at)
  where revoked_at is null;

-- One immutable evidence record per automatic violation, linked to the sanction it caused.
create table if not exists public.kapli_sanction_evidence (
  id bigint generated by default as identity primary key,
  sanction_id bigint not null references public.kapli_sanctions(id) on delete cascade,
  violation_id bigint not null unique references public.kapli_moderation_violations(id) on delete cascade,
  source text not null,
  source_id bigint,
  violation_type text not null,
  body_snapshot text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists kapli_sanction_evidence_sanction_idx
  on public.kapli_sanction_evidence(sanction_id, created_at desc);

-- Backfill evidence already stored in the existing violation history.
-- A violation is attached only to an automatic mute that was active at that timestamp.
insert into public.kapli_sanction_evidence
  (sanction_id, violation_id, source, source_id, violation_type, body_snapshot, created_at)
select s.id, v.id, v.source, v.source_id, v.violation_type, v.body_snapshot, v.created_at
from public.kapli_moderation_violations v
join lateral (
  select sa.id
  from public.kapli_sanctions sa
  where sa.user_id = v.user_id
    and sa.kind = 'mute'
    and sa.source = 'automatic'
    and sa.created_at <= v.created_at + interval '1 minute'
    and sa.ends_at >= v.created_at
    and (sa.revoked_at is null or sa.revoked_at >= v.created_at)
  order by sa.created_at desc
  limit 1
) s on true
on conflict (violation_id) do nothing;

alter table public.kapli_sanction_evidence enable row level security;
revoke all on public.kapli_sanction_evidence from public, anon, authenticated;

-- Append-only staff action journal. Direct table access is not granted to browser roles.
create table if not exists public.kapli_moderation_actions (
  id bigint generated by default as identity primary key,
  action text not null,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_role text not null,
  target_user_id uuid references auth.users(id) on delete set null,
  sanction_id bigint references public.kapli_sanctions(id) on delete set null,
  sanction_kind text,
  reason text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists kapli_mod_actions_created_idx
  on public.kapli_moderation_actions(created_at desc);
alter table public.kapli_moderation_actions enable row level security;
revoke all on public.kapli_moderation_actions from public, anon, authenticated;

