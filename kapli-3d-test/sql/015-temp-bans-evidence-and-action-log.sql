-- Temporary account ban duration is deliberately limited to 1–7 days (1440–10080 minutes).
-- Moderator: issue/revoke mute only. Administrator: issue/revoke mute, temporary ban and permanent ban.
-- Chat Arbiter: automatic temporary mutes only. Exact matched phrases are retained in sanction evidence.
